CREATE EXTENSION IF NOT EXISTS unaccent;

create table house_units
(
    id           bigint generated by default as identity primary key,
    code         varchar(255) not null,
    display_name varchar(255) not null,
    address      varchar(255) not null,

    constraint uk_house_units_code UNIQUE (code)
);

create table beneficiaries
(
    -- PK
    id                       bigint generated by default as identity primary key,

    -- Core identity
    first_name               varchar(255) not null,
    last_name                varchar(255) not null,
    amka                     varchar(11)  not null,
    date_of_birth            date         not null,

    -- Status / classification
    is_active                boolean      not null,
    -- TODO(#3): Replace CHECK with PostgreSQL ENUM when domain values stabilize.
    house_unit_id            bigint       not null,

    -- Permanent address
    perm_street              varchar(255) not null,
    perm_street_number       varchar(255) not null,
    perm_city                varchar(255) not null,
    perm_zip_code            varchar(255) not null,

    -- Emergency contact
    emergency_first_name     varchar(255) not null,
    emergency_last_name      varchar(255) not null,
    emergency_relationship   varchar(255) not null
        constraint chk_beneficiaries_emergency_relationship
            check ((emergency_relationship)::text = any
                   ((array [
                       'PARENT'::character varying,
                       'SIBLING'::character varying,
                       'OTHER_RELATIVE'::character varying,
                       'FRIEND'::character varying,
                       'SOCIAL_WORKER'::character varying,
                       'OTHER'::character varying
                       ])::text[])),
    emergency_mobile_number  varchar(255),
    emergency_landline_phone varchar(255),
    emergency_email          varchar(255),
    emergency_street         varchar(255) not null,
    emergency_street_number  varchar(255),
    emergency_city           varchar(255) not null,
    emergency_zip_code       varchar(255) not null,

    constraint uk_beneficiaries_amka unique (amka),
    constraint fk_beneficiaries_house_unit FOREIGN KEY (house_unit_id) REFERENCES house_units (id)
);

create table allergies
(
    beneficiary_id bigint       not null
        constraint fk_allergies_beneficiary
            references beneficiaries (id) on delete cascade,
    id             bigint generated by default as identity
        primary key,
    reaction       varchar(255) not null,
    severity       varchar(255) not null
        constraint chk_allergies_severity
            check ((severity)::text = ANY
                   ((ARRAY [
                       'LOW':: character varying,
                       'MEDIUM':: character varying,
                       'HIGH':: character varying
                       ])::text[])
                ),
    substance      varchar(255) not null
);

create table medications
(
    beneficiary_id       bigint       not null
        constraint fk_medication_beneficiary
            references beneficiaries (id) on delete cascade,
    id                   bigint generated by default as identity
        primary key,
    administration_times varchar(255) not null,
    dosage               varchar(255) not null,
    frequency            varchar(255) not null,
    instructions         varchar(255),
    name                 varchar(255) not null
);

create table legal_representatives
(
    id             bigint generated by default as identity primary key,
    afm            varchar(11)  not null
        constraint uk_legal_representatives_afm unique,
    type           varchar(255) not null
        constraint chk_legal_representatives_type
            check ((type)::text = ANY
                   ((ARRAY [
                       'JUDICIAL_SUPPORTER':: character varying,
                       'LEGAL_GUARDIAN':: character varying,
                       'PUBLIC_AUTHORITY':: character varying,
                       'OTHER':: character varying
                       ])::text[])
                ),
    first_name     varchar(255) not null,
    last_name      varchar(255) not null,
    mobile_number  varchar(20),
    landline_phone varchar(20),
    email          varchar(255)
        constraint uk_legal_representatives_email unique,
    notes          text
);

create table beneficiary_legal_representatives
(
    beneficiary_id          bigint not null,
    legal_representative_id bigint not null,

    constraint pk_beneficiary_legal_representatives
        primary key (beneficiary_id, legal_representative_id),

    constraint fk_beneficiary_legal_representatives_beneficiary
        foreign key (beneficiary_id)
            references beneficiaries (id)
            on delete cascade,

    constraint fk_beneficiary_legal_representatives_legal_representative
        foreign key (legal_representative_id)
            references legal_representatives (id)
            on delete cascade
);

create table roles
(
    id          bigint generated by default as identity
        primary key,
    description varchar(255),
    name        varchar(255) not null
        constraint uk_roles_name unique
        constraint chk_roles_name
            CHECK ((name)::TEXT = ANY
                   ((ARRAY [
                       'ROLE_ADMIN'::CHARACTER VARYING,
                       'ROLE_MANAGER'::CHARACTER VARYING,
                       'ROLE_STAFF'::CHARACTER VARYING
                       ])::text[])
                )
);

create table users
(
    active     boolean      not null,
    id         bigint generated by default as identity
        primary key,
    email      varchar(255) not null,
    first_name varchar(255) not null,
    last_name  varchar(255) not null,
    mobile     varchar(255),
    password   varchar(255) not null,
    username   varchar(255) not null,

    constraint uk_users_username unique (username),
    constraint uk_users_email unique (email)
);

create table user_roles
(
    role_id bigint not null
        constraint fk_user_roles_role
            references roles (id) on delete cascade,
    user_id bigint not null
        constraint fk_user_roles_user
            references users (id) on delete cascade,
    constraint pk_user_roles primary key (role_id, user_id)
);

create table employees
(
    id            bigint generated by default as identity
        primary key,
    first_name    varchar(255) not null,
    last_name     varchar(255) not null,
    email         varchar(255) not null,
    mobile_number varchar(255) not null,

    street        varchar(255) not null,
    street_number varchar(255),
    city          varchar(255) not null,
    zip_code          varchar(255) not null,

    position      varchar(255) not null,
    constraint chk_position_name
        CHECK ((position)::TEXT = ANY
               ((ARRAY [
                   'CAREGIVER'::CHARACTER VARYING,
                   'SOCIAL_WORKER'::CHARACTER VARYING,
                   'PSYCHOLOGIST'::CHARACTER VARYING,
                   'PSYCHIATRIST'::CHARACTER VARYING,
                   'EDUCATOR'::CHARACTER VARYING,
                   'HOUSE_MANAGER'::CHARACTER VARYING,
                   'ADMINISTRATIVE_STAFF'::CHARACTER VARYING
                   ])::text[])
            ),
    hire_date     date         not null,
    is_active     boolean      not null,
    constraint uk_employees_email unique (email)
);

create table employee_house_units
(
    employee_id   bigint not null
        constraint fk_employee_house_units_employee
            references employees (id) on delete cascade,
    house_unit_id bigint not null
        constraint fk_employee_house_units_house_unit
            references house_units (id) on delete cascade,
    constraint pk_employee_house_units
        primary key (employee_id, house_unit_id)
);
